import Foundation

// MARK: - 'Mindy's Photos' — struct vs class

struct Photo {
    var roverX: Int
}

class PhotoClass {
    var roverX: Int
    
    init(roverX: Int) {
        self.roverX = roverX
    }
}

func mindyStruct() -> (day1: Int, day2: Int) {
    var x = Photo(roverX: 100)       // Снимок 1: ровер у Hab
    var y = x                        // Снимок 2: независимая КОПИЯ
    y.roverX = 500                   // Ровер переехал на новом снимке
    return (x.roverX, y.roverX)
}

func mindyClass() -> (day1: Int, day2: Int) {
    let x = PhotoClass(roverX: 100)   // Снимок 1: ровер у Hab
    let y = x                         // Снимок 2: ТА ЖЕ ССЫЛКА на объект
    y.roverX = 500                    // Ровер «переехал» — но объект один и тот же
    return (x.roverX, y.roverX)
}

// MARK: - Точка входа (Исполняемый код)

func compare() {
    let structResult = mindyStruct()
    print("struct: x=\(structResult.day1), y=\(structResult.day2) -> \(structResult.day1 != structResult.day2 ? "Разница есть! Марк жив!" : "Разницы нет")")
    
    let classResult = mindyClass()
    print("class:  x=\(classResult.day1), y=\(classResult.day2) -> \(classResult.day1 == classResult.day2 ? "Разницы нет, архив перезаписан..." : "Разница есть")")
}

/* 📝 ИТОГОВЫЕ ОТВЕТЫ НА ВОПРОСЫ:

 1️⃣ В каком случае Минди УВИДИТ разницу между снимками (x ≠ y)?
    — В случае со STRUCT (x=100, y=500). Так как это тип значения (Value Type), изменение
      координаты на втором снимке (y) никак не затронуло первый снимок (x). Минди видит движение.

 2️⃣ В каком случае НЕ увидит (x == y)?
    — В случае с CLASS (x=500, y=500). Изменение свойства в `y` перезаписало данные и в `x`,
      так как обе переменные ссылаются на один экземпляр в памяти (Heap).

 3️⃣ Какой тип — struct или class — правильный для АРХИВНЫХ СНИМКОВ?
    — Исключительно STRUCT. Архивные исторические данные должны обладать Value Semantics.
      Они обязаны быть иммутабельными (неизменяемыми) по отношению к новым кадрам. Новый снимок
      не должен портить или перезаписывать старый архив.

 4️⃣ А какой — для ЖИВОГО ровера, за которым все наблюдают в реальном времени?
    — Для живого физического объекта на Марсе нужен CLASS (Reference Semantics). Ровер в реальности
      существует в единственном экземпляре. Если Хьюстон меняет его состояние или Марк садится за руль,
      все службы на Земле должны видеть эти изменения в реальном времени на одном общем объекте.
 
--------
 
 🚀 ПОЧЕМУ APPLE И SWIFT-РАЗРАБОТЧИКИ ТАК ЛЮБЯТ VALUE SEMANTICS (СТРУКТУРЫ)?

 1. Безопасность в многопоточности (Thread Safety):
    Разные потоки процессора могут безопасно изменять свои копии данных без риска поймать Race Condition.
 
 2. Предсказуемость кода:
    Вы гарантированно уверены, что внешняя функция не изменит «втихаря» переданный в неё массив или модель.
 
 3. Локальное рассуждение (Local Reasoning):
    Чтобы понять поведение переменной, достаточно увидеть текущую функцию, не прочесывая весь проект.
 
 4. Оптимизация памяти (Copy-on-Write):
    Swift не копирует тяжелые коллекции (Array, Dictionary) в памяти вхолостую, а делает это только при мутации.
    Копирование при записи — CoW: это умный механизм оптимизации памяти в Swift. Его гл. задача — сделать так, чтобы Value Semantics (копирование объектов) работала молниеносно быстро и не забивала ОП.
 
 😟 В чем проблема без CoW?
 В Swift массивы, словари и строки — это структуры (Value Types). По правилам значимой семантики, при присвоении они должны полностью копироваться. Есть массив 10 млн. фото Марса = 1 Гб. Копия -> программа зависла, а ОП Айфона мгновенно закончилась.
 
 😎 Как решает проблему Copy-on-Write?
 Когда пишу var archiveB = archiveA, реального копирования в памяти НЕ происходит. Оба массива в этот момент начинают тихонько ссылаться на один и тот же адрес в памяти, как будто это классы. Если вы просто читаете данные из archiveB (напр., выводите на экран фотографии), они так и продолжают делить одну память на двоих. Скорость операции — мгновенная.
 
 ⚡ Момент "On-Write" (При записи)
 Копирование происходит only тогда, когда один из массивов пытается ИЗМЕНИТЬ свои данные (срабатывает "Write").
 Если вы решите удалить одну фотографию из archiveB:
 1. Swift видит: «Ой, на эту память сейчас ссылается два массива (archiveA и archiveB), а один из них хочет внести изменения!»
 2. Именно в этот момент Swift выделяет память, копирует туда массив и только после этого применяет изменения к archiveB.
 3. Теперь у archiveA свой старый 1 ГБ данных, а у archiveB — своя новая измененная копия.
 
 ⚠️ Важный нюанс: CoW НЕ работает для структур «из коробки»
 В Swift механизм CoW auto встроен только в стандартные системные коллекции: Array, Dictionary, Set, String.
 Если вы создадите свою огромную структуру c кучей кастомных полей..., При её присвоении var b = a она будет честно и тяжело copy в памяти каждый раз без всякого CoW. Чтобы добавить CoW в свою структуру, разработчикам приходится писать спец. код-обертку, используя ссылочный тип (class) внутри структуры для хранения данных. Вручную реализовать Copy-on-Write для своей кастомной структуры можно с помощью приватного класса и свойства isKnownUniquelyReferenced.
